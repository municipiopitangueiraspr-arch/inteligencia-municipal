CREATE OR REPLACE FUNCTION public.municipal_governance_save_org_unit(p_id text,p_parent_id text,p_code text,p_name text,p_unit_type text,p_description text,p_sort_order integer,p_is_active boolean)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public AS $$
BEGIN
 IF NOT public.municipal_governance_is_admin() THEN RAISE EXCEPTION 'Acesso administrativo obrigatório' USING ERRCODE='42501'; END IF;
 IF nullif(btrim(p_id),'') IS NULL OR nullif(btrim(p_code),'') IS NULL OR nullif(btrim(p_name),'') IS NULL THEN RAISE EXCEPTION 'Código e nome da unidade são obrigatórios'; END IF;
 IF p_parent_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM public.municipal_org_units WHERE id=p_parent_id) THEN RAISE EXCEPTION 'Unidade superior não encontrada'; END IF;
 IF p_unit_type NOT IN ('MUNICIPIO','ORGAO','SECRETARIA','DEPARTAMENTO','DIVISAO','ASSESSORIA','COMISSAO','UNIDADE') THEN RAISE EXCEPTION 'Tipo de unidade inválido'; END IF;
 INSERT INTO public.municipal_org_units(id,parent_id,code,name,unit_type,description,sort_order,is_active,updated_at)
 VALUES(lower(btrim(p_id)),p_parent_id,btrim(p_code),btrim(p_name),p_unit_type,coalesce(btrim(p_description),''),coalesce(p_sort_order,0),coalesce(p_is_active,true),now())
 ON CONFLICT(id) DO UPDATE SET parent_id=EXCLUDED.parent_id,code=EXCLUDED.code,name=EXCLUDED.name,unit_type=EXCLUDED.unit_type,description=EXCLUDED.description,sort_order=EXCLUDED.sort_order,is_active=EXCLUDED.is_active,updated_at=now();
 INSERT INTO public.municipal_access_audit(actor_user_id,action,details) VALUES(auth.uid(),'ORG_UNIT_SAVE',jsonb_build_object('id',p_id,'name',p_name,'active',p_is_active));
END $$;
REVOKE ALL ON FUNCTION public.municipal_governance_save_org_unit(text,text,text,text,text,text,integer,boolean) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.municipal_governance_save_org_unit(text,text,text,text,text,text,integer,boolean) TO authenticated;

