CREATE OR REPLACE FUNCTION public.census_user_can_access_lot(p_lot_id uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=pg_catalog,public,app_private,auth AS $$
 SELECT auth.uid() IS NOT NULL AND (
   coalesce(app_private.current_user_is_admin(), false)
   OR (
     public.municipal_user_has_module('census')
     AND EXISTS (
       SELECT 1 FROM public.census_map_lots lot
       JOIN public.census_map_imports map_import ON map_import.id=lot.import_id AND map_import.is_current IS TRUE AND map_import.status='PUBLISHED' AND map_import.division_saved_at IS NOT NULL
       JOIN public.census_zones zone ON zone.id=lot.zone_id AND zone.active IS TRUE
       JOIN public.census_acs_zone_assignments assignment ON assignment.zone_id=lot.zone_id AND assignment.active IS TRUE
       JOIN public.census_acs acs ON acs.id=assignment.acs_id AND acs.active IS TRUE
       WHERE lot.id=p_lot_id AND lot.is_valid IS TRUE
         AND nullif(lower(btrim(acs.email)),'')=nullif(lower(btrim(auth.jwt() ->> 'email')),'')
     )
   )
 )
$$;

CREATE OR REPLACE FUNCTION public.census_user_can_access_import(p_import_id uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=pg_catalog,public,app_private,auth AS $$
 SELECT auth.uid() IS NOT NULL AND (
   coalesce(app_private.current_user_is_admin(), false)
   OR (public.municipal_user_has_module('census') AND EXISTS (
     SELECT 1 FROM public.census_map_lots lot JOIN public.census_map_imports map_import ON map_import.id=lot.import_id AND map_import.is_current IS TRUE AND map_import.status='PUBLISHED' AND map_import.division_saved_at IS NOT NULL
     WHERE lot.import_id=p_import_id AND lot.is_valid IS TRUE AND public.census_user_can_access_lot(lot.id)
   ))
 )
$$;

