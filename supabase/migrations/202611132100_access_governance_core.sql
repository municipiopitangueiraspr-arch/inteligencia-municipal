CREATE OR REPLACE FUNCTION public.municipal_user_has_role(p_role_id text)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=pg_catalog,public,auth AS $$
 SELECT auth.uid() IS NOT NULL AND (
   public.municipal_governance_is_admin()
   OR EXISTS (
     SELECT 1 FROM public.municipal_user_assignments a JOIN public.usuarios u ON u.id=a.user_id
     WHERE u.uuid=auth.uid() AND u.ativo IS TRUE AND a.role_id=p_role_id AND a.active IS TRUE
       AND current_date BETWEEN a.valid_from AND COALESCE(a.valid_until,current_date)
   )
 )
$$;

CREATE OR REPLACE FUNCTION public.municipal_user_has_module(p_module_id text)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=pg_catalog,public,auth AS $$
 SELECT auth.uid() IS NOT NULL AND (
   public.municipal_governance_is_admin()
   OR EXISTS (
     SELECT 1 FROM public.municipal_assignment_modules am
     JOIN public.municipal_user_assignments a ON a.id=am.assignment_id
     JOIN public.usuarios u ON u.id=a.user_id
     WHERE u.uuid=auth.uid() AND u.ativo IS TRUE AND am.module_id=p_module_id AND a.active IS TRUE
       AND current_date BETWEEN a.valid_from AND COALESCE(a.valid_until,current_date)
   )
   OR EXISTS (
     SELECT 1 FROM public.municipal_user_modules um JOIN public.usuarios u ON u.id=um.user_id
     WHERE u.uuid=auth.uid() AND u.ativo IS TRUE AND um.module_id=p_module_id
   )
 )
$$;
REVOKE ALL ON FUNCTION public.municipal_user_has_role(text) FROM PUBLIC,anon;
REVOKE ALL ON FUNCTION public.municipal_user_has_module(text) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.municipal_user_has_role(text),public.municipal_user_has_module(text) TO authenticated;

CREATE OR REPLACE FUNCTION public.municipal_governance_list_org_units()
RETURNS TABLE(id text,parent_id text,code text,name text,unit_type text,description text,sort_order integer,is_active boolean)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=pg_catalog,public AS $$
BEGIN
 IF NOT public.municipal_governance_is_admin() THEN RAISE EXCEPTION 'Acesso administrativo obrigatório' USING ERRCODE='42501'; END IF;
 RETURN QUERY SELECT o.id,o.parent_id,o.code,o.name,o.unit_type,o.description,o.sort_order,o.is_active FROM public.municipal_org_units o ORDER BY o.sort_order,o.name LIMIT 500;
END $$;
