CREATE TABLE IF NOT EXISTS public.municipal_org_units (
  id text PRIMARY KEY,
  parent_id text REFERENCES public.municipal_org_units(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  code text NOT NULL,
  name text NOT NULL,
  unit_type text NOT NULL CHECK (unit_type IN ('MUNICIPIO','ORGAO','SECRETARIA','DEPARTAMENTO','DIVISAO','ASSESSORIA','COMISSAO','UNIDADE')),
  description text NOT NULL DEFAULT '',
  sort_order integer NOT NULL DEFAULT 0,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS municipal_org_units_parent_idx ON public.municipal_org_units(parent_id);
CREATE INDEX IF NOT EXISTS municipal_org_units_active_idx ON public.municipal_org_units(is_active);

CREATE TABLE IF NOT EXISTS public.municipal_roles (
  id text PRIMARY KEY,
  label text NOT NULL,
  description text NOT NULL DEFAULT '',
  is_system boolean NOT NULL DEFAULT true,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.municipal_permissions (
  id text PRIMARY KEY,
  label text NOT NULL,
  description text NOT NULL DEFAULT '',
  module_id text REFERENCES public.municipal_modules(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.municipal_role_permissions (
  role_id text NOT NULL REFERENCES public.municipal_roles(id) ON UPDATE CASCADE ON DELETE CASCADE,
  permission_id text NOT NULL REFERENCES public.municipal_permissions(id) ON UPDATE CASCADE ON DELETE CASCADE,
  PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE IF NOT EXISTS public.municipal_user_assignments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id integer NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  org_unit_id text NOT NULL REFERENCES public.municipal_org_units(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  role_id text NOT NULL REFERENCES public.municipal_roles(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  active boolean NOT NULL DEFAULT true,
  valid_from date NOT NULL DEFAULT current_date,
  valid_until date,
  created_by uuid REFERENCES auth.users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (valid_until IS NULL OR valid_until >= valid_from)
);

CREATE UNIQUE INDEX IF NOT EXISTS municipal_user_assignments_active_unique
  ON public.municipal_user_assignments(user_id, org_unit_id, role_id)
  WHERE active IS TRUE;
CREATE INDEX IF NOT EXISTS municipal_user_assignments_user_idx ON public.municipal_user_assignments(user_id, active);
CREATE INDEX IF NOT EXISTS municipal_user_assignments_org_idx ON public.municipal_user_assignments(org_unit_id, active);

CREATE TABLE IF NOT EXISTS public.municipal_assignment_modules (
  assignment_id uuid NOT NULL REFERENCES public.municipal_user_assignments(id) ON DELETE CASCADE,
  module_id text NOT NULL REFERENCES public.municipal_modules(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (assignment_id, module_id)
);

CREATE TABLE IF NOT EXISTS public.municipal_assignment_scopes (
  assignment_id uuid NOT NULL REFERENCES public.municipal_user_assignments(id) ON DELETE CASCADE,
  scope_type text NOT NULL,
  scope_key text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (assignment_id, scope_type, scope_key)
);

CREATE TABLE IF NOT EXISTS public.municipal_access_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_user_id uuid,
  target_user_id integer,
  assignment_id uuid,
  action text NOT NULL,
  details jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS municipal_access_audit_created_idx ON public.municipal_access_audit(created_at DESC);
CREATE INDEX IF NOT EXISTS municipal_access_audit_target_idx ON public.municipal_access_audit(target_user_id, created_at DESC);

